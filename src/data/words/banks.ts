/** 词库：考研 / 四六级 / 雅思 / 自定义（可继续扩包）；difficulty 1易→5难，供无尽模式递进 */
import type { ExamWord } from '../../lib/personal-exam-vocab'
import { readWordStudy, updateWordStudy } from '../../services/words/study-storage'

export type WordBankId = 'kaoyan' | 'cet4' | 'cet6' | 'ielts' | 'custom'

export type WordDifficulty = 1 | 2 | 3 | 4 | 5

export interface WordEntry {
  id: string
  word: string
  phonetic: string
  meaning: string
  bank: WordBankId
  difficulty: WordDifficulty
  example?: string
}

const EXAM_BANKS: Record<ExamWord['exam_type'], WordBankId> = { 'CET-4': 'cet4', 'CET-6': 'cet6', 'KAOYAN-1': 'kaoyan', 'KAOYAN-2': 'kaoyan', IELTS: 'ielts' }
let downloadedWords: WordEntry[] = []
let bankRevision = 0
let mergedBank: WordEntry[] | null = null
let lastCustomJson: string | null = null

export function downloadedBankForExam(exam: ExamWord['exam_type']): WordBankId {
  return EXAM_BANKS[exam]
}

/** Use original IDs/difficulty for overlaps so existing SRS and games keep their cards. */
export function setDownloadedWordBank(rows: ExamWord[]): void {
  const builtIn = new Map(WORD_BANK.map(word => [`${word.bank}:${word.word.trim().toLowerCase()}`, word]))
  const unique = new Map<string, WordEntry>()
  for (const row of rows) {
    const bank = EXAM_BANKS[row.exam_type]
    if (!bank || !row.word?.trim() || !row.meaning?.trim()) continue
    const key = `${bank}:${row.word.trim().toLowerCase()}`
    const original = builtIn.get(key)
    unique.set(key, { id: original?.id ?? key, bank, word: row.word, phonetic: row.phonetic || original?.phonetic || '', meaning: row.meaning, difficulty: original?.difficulty ?? (bank === 'cet4' ? 2 : 3), example: row.example })
  }
  downloadedWords = [...unique.values()]
  mergedBank = null
  bankRevision++
}

export function getWordBankRevision(): number { return bankRevision }

