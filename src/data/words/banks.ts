/** 读取当前账号的自定义单词 */
export function loadCustomWords(): WordEntry[] {
  return readWordStudy().customWords
}

/** 保存当前账号的自定义单词 */
export function saveCustomWords(words: WordEntry[]): void {
  updateWordStudy((bundle) => { bundle.customWords = words })
}

/** 添加一个自定义单词，返回新列表；若已存在同 bank:word 则跳过 */
export function addCustomWord(word: string, phonetic: string, meaning: string, difficulty: WordDifficulty = 2): WordEntry[] {
  const id = `custom:${word.toLowerCase()}`
  const entry: WordEntry = { id, word: word.trim(), phonetic: phonetic.trim(), meaning: meaning.trim(), bank: 'custom', difficulty }
  return updateWordStudy((bundle) => {
    if (bundle.customWords.some((w) => w.id === id)) return bundle.customWords
    bundle.customWords = [...bundle.customWords, entry]
    return bundle.customWords
  })
}

/** 删除一个自定义单词 */
export function removeCustomWord(id: string): WordEntry[] {
  return updateWordStudy((bundle) => {
    bundle.customWords = bundle.customWords.filter((w) => w.id !== id)
    return bundle.customWords
  })
}

/**
 * 解析批量导入文本，每行一条，支持多种分隔格式：
 *   word /phonetic/ meaning
 *   word meaning
 *   word, meaning
 *   word	meaning（Tab 分隔）
 * 返回成功解析的单词条目列表。
 */
export function parseBulkWords(text: string): { word: string; phonetic: string; meaning: string }[] {
  const lines = text.split(/\r?\n/)
  const result: { word: string; phonetic: string; meaning: string }[] = []
  for (const raw of lines) {
    const line = raw.trim()
    if (!line) continue
    // 尝试匹配 word /phonetic/ meaning
    const phoneticMatch = line.match(/^(\S+)\s+(\/[^/]+\/)\s+(.+)$/)
    if (phoneticMatch) {
      result.push({ word: phoneticMatch[1], phonetic: phoneticMatch[2], meaning: phoneticMatch[3].trim() })
      continue
    }
    // 尝试 word, meaning 或 word	meaning 或 word meaning（取第一个空格/逗号/Tab 分隔）
    const sepMatch = line.match(/^(\S+)[\s,，\t]+(.+)$/)
    if (sepMatch) {
      result.push({ word: sepMatch[1], phonetic: '', meaning: sepMatch[2].trim() })
    }
  }
  return result
}

/** 批量添加自定义单词，返回新增数量（去重后） */
export function addBulkCustomWords(items: { word: string; phonetic: string; meaning: string }[]): number {
  return updateWordStudy((bundle) => {
    const map = new Map(bundle.customWords.map((w) => [w.id, w]))
    let added = 0
    for (const it of items) {
      const id = `custom:${it.word.toLowerCase()}`
      if (!map.has(id) && it.word && it.meaning) {
        map.set(id, { id, word: it.word.trim(), phonetic: (it.phonetic || '').trim(), meaning: it.meaning.trim(), bank: 'custom', difficulty: 2 })
        added++
      }
    }
    bundle.customWords = Array.from(map.values())
    return added
  })
}

/** 内置 + 自定义合并词库（运行时使用） */
export function getWordBank(): WordEntry[] {
  const customJson = JSON.stringify(loadCustomWords())
  if (mergedBank && customJson === lastCustomJson) return mergedBank
  const entries = new Map(WORD_BANK.map(word => [`${word.bank}:${word.word.trim().toLowerCase()}`, word]))
  for (const word of downloadedWords) entries.set(`${word.bank}:${word.word.trim().toLowerCase()}`, word)
  for (const word of loadCustomWords()) entries.set(word.id, word)
  lastCustomJson = customJson
  mergedBank = [...entries.values()]
  return mergedBank
}

