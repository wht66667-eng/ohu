/** Run the real migration in an isolated PostgreSQL WASM engine, never CloudBase. */
import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync, existsSync, mkdirSync, writeFileSync, unlinkSync } from 'node:fs'
import { createRequire } from 'node:module'
import { createHash } from 'node:crypto'
import { resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = resolve(fileURLToPath(new URL('..', import.meta.url)))
const require = createRequire(import.meta.url)
let runtime
try { runtime = require.resolve('@electric-sql/pglite') } catch {
  const isolated = resolve(root, '.codex/qa/friends131-pg/node_modules/@electric-sql/pglite/dist/index.js')
  if (!existsSync(isolated)) throw Error('Install the isolated SQL test runtime: npm install --prefix .codex/qa/friends131-pg --no-save --package-lock=false --ignore-scripts @electric-sql/pglite@0.5.11')
  runtime = isolated
}
const { PGlite } = await import(pathToFileURL(runtime).href)
const migration = readFileSync(resolve(root, 'docs/sql/friends-authorization-131.sql'), 'utf8')
const migrationHash = createHash('sha256').update(migration).digest('hex')
const seed = `
  CREATE ROLE authenticated NOLOGIN; CREATE ROLE anon NOLOGIN;
  CREATE ROLE friend_client_inherited NOLOGIN INHERIT;
  GRANT authenticated TO friend_client_inherited;
  CREATE SCHEMA auth;
  CREATE FUNCTION auth.uid() RETURNS text LANGUAGE sql STABLE AS $$
    SELECT nullif(current_setting('request.jwt.claim.sub', true), '')
  $$;
  GRANT USAGE ON SCHEMA public, auth TO authenticated, anon;
  REVOKE CREATE ON SCHEMA public FROM PUBLIC;
  CREATE TABLE public.friend_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_uid text NOT NULL, from_name text, from_avatar text, to_uid text NOT NULL,
    status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','accepted','rejected')),
    message text, created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
  );
  CREATE TABLE public.friends (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_uid text NOT NULL, friend_uid text NOT NULL, friend_name text, friend_avatar text,
    remark text, created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
  );
  CREATE UNIQUE INDEX friends_pair ON public.friends(user_uid,friend_uid);
  CREATE UNIQUE INDEX friend_requests_pending_pair ON public.friend_requests(from_uid,to_uid) WHERE status='pending';
  CREATE TABLE public.moments (id bigint PRIMARY KEY, creator_uid text NOT NULL, body text, visibility text NOT NULL);
  CREATE TABLE public.moments_likes (id bigint PRIMARY KEY, moment_id bigint, liker_uid text);
  CREATE TABLE public.moments_comments (id bigint PRIMARY KEY, moment_id bigint, commenter_uid text);
  ALTER TABLE public.friends ENABLE ROW LEVEL SECURITY;
  ALTER TABLE public.friend_requests ENABLE ROW LEVEL SECURITY;
  ALTER TABLE public.moments ENABLE ROW LEVEL SECURITY;
  ALTER TABLE public.moments_likes ENABLE ROW LEVEL SECURITY;
  ALTER TABLE public.moments_comments ENABLE ROW LEVEL SECURITY;
  GRANT SELECT,INSERT,UPDATE,DELETE,TRIGGER,TRUNCATE ON public.friends,public.friend_requests TO authenticated;
  GRANT SELECT ON public.moments TO authenticated;
  GRANT USAGE,SELECT ON ALL SEQUENCES IN SCHEMA public TO authenticated;
  CREATE POLICY friend_requests_insert_own ON public.friend_requests FOR INSERT TO authenticated WITH CHECK (from_uid=auth.uid());
  CREATE POLICY friend_requests_select_own ON public.friend_requests FOR SELECT TO authenticated USING (from_uid=auth.uid() OR to_uid=auth.uid());
  CREATE POLICY friend_requests_update_own ON public.friend_requests FOR UPDATE TO authenticated USING (to_uid=auth.uid()) WITH CHECK (to_uid=auth.uid());
  CREATE POLICY friends_insert_own ON public.friends FOR INSERT TO authenticated WITH CHECK (user_uid=auth.uid());
  CREATE POLICY friends_select_own ON public.friends FOR SELECT TO authenticated USING (user_uid=auth.uid() OR friend_uid=auth.uid());
  CREATE POLICY friends_delete_own ON public.friends FOR DELETE TO authenticated USING (user_uid=auth.uid() OR friend_uid=auth.uid());
  INSERT INTO public.friend_requests(id,from_uid,to_uid,status,message) VALUES (900,'historical-A','historical-B','accepted','preserve'),(901,'old-half-A','old-half-B','rejected','do not guess ownership');
  INSERT INTO public.friends(id,user_uid,friend_uid,friend_name) VALUES (900,'historical-B','historical-A','preserve'),(901,'old-half-B','old-half-A','preserve historical row');
  INSERT INTO public.moments VALUES (1,'author','friends only','friends_only'),(2,'author','private','private'),(3,'author','public','public');
`

test('131 friendship RLS and atomic triggers block forgery, preserve history and remain compatible with the 130 client', async t => {
  const proofPath = resolve(root,'.codex/qa/friends131-sql-test.json')
  if (existsSync(proofPath)) unlinkSync(proofPath)
  const db = new PGlite(), results = []
  const ownerQuery = (sql, params = []) => db.query(sql, params)
  const asRole = async (role, uid, sql, params = []) => {
    if (!['authenticated','friend_client_inherited'].includes(role)) throw Error('Unexpected isolated role')
    await db.exec(`SET ROLE ${role}`)
    await db.query("SELECT set_config('request.jwt.claim.sub',$1,false)", [uid])
    try { return await db.query(sql, params) }
    finally { await db.exec("RESET ROLE; RESET request.jwt.claim.sub") }
  }
  const as = (uid, sql, params = []) => asRole('authenticated',uid,sql,params)
  const rejects = async promise => assert.rejects(promise, error => error.code === '42501')
  const caseOf = async (name, run) => {
    let passed = false
    await t.test(name, async () => { await run(); passed = true })
    results.push({ name, passed })
    if (!passed) throw Error(`Isolated PostgreSQL case failed: ${name}`)
  }
  const insertRequest = async (sender, recipient) => (await as(sender,
    "INSERT INTO public.friend_requests(from_uid,to_uid,status,from_name) VALUES ($1,$2,'pending',$3) RETURNING id", [sender, recipient, `Name ${sender}`])).rows[0].id
  const decide = (recipient, id, status) => as(recipient, "UPDATE public.friend_requests SET status=$2 WHERE id=$1 AND to_uid=$3 AND status='pending' RETURNING id,status", [id, status, recipient])
  const countPair = async (a, b) => Number((await ownerQuery('SELECT count(*) AS n FROM public.friends WHERE (user_uid=$1 AND friend_uid=$2) OR (user_uid=$2 AND friend_uid=$1)', [a,b])).rows[0].n)
  try {
    await db.exec(seed)
    await db.exec(readFileSync(resolve(root, 'docs/sql/moments-visibility-130.sql'), 'utf8'))
    const before = JSON.stringify((await ownerQuery('SELECT * FROM public.friends ORDER BY id')).rows)
    const beforeRequests = JSON.stringify((await ownerQuery('SELECT * FROM public.friend_requests ORDER BY id')).rows)
    await db.exec(migration)

    await caseOf('migration preserves all historical accepted and unclassified partial rows exactly', async () => {
      assert.equal(JSON.stringify((await ownerQuery('SELECT * FROM public.friends ORDER BY id')).rows), before)
      assert.equal(JSON.stringify((await ownerQuery('SELECT * FROM public.friend_requests ORDER BY id')).rows), beforeRequests)
    })
    await caseOf('request INSERT cannot claim accepted/rejected, target self or have a blank recipient', async () => {
      for (const [from,to,status] of [['attacker','author','accepted'],['attacker','author','rejected'],['attacker','attacker','pending'],['attacker',' ','pending'],['other','author','pending']]) {
        await rejects(as('attacker', 'INSERT INTO public.friend_requests(from_uid,to_uid,status) VALUES ($1,$2,$3)', [from,to,status]))
      }
    })
    await caseOf('arbitrary friend-edge INSERT cannot create a relationship or gain private feed access', async () => {
      await rejects(as('attacker', "INSERT INTO public.friends(user_uid,friend_uid) VALUES ('attacker','author')"))
      assert.equal(await countPair('attacker','author'), 0)
      assert.deepEqual((await as('attacker', 'SELECT id FROM public.moments ORDER BY id')).rows.map(row => row.id), [3])
    })
    await caseOf('only the recipient may decide; participants, id, text and timestamp are immutable', async () => {
      const id = await insertRequest('sender','recipient')
      assert.equal((await decide('sender',id,'accepted')).rows.length, 0)
      for (const update of ["from_uid='author'","to_uid='other'","id=9999","message='forged'","created_at=CURRENT_TIMESTAMP + interval '1 day'"]) {
        await rejects(as('recipient', `UPDATE public.friend_requests SET status='accepted',${update} WHERE id=$1`, [id]))
      }
      assert.equal((await ownerQuery('SELECT status FROM public.friend_requests WHERE id=$1',[id])).rows[0].status, 'pending')
      assert.equal(await countPair('sender','recipient'), 0)
    })
    await caseOf('roles inheriting authenticated cannot change request participants or details while rejecting', async () => {
      const id=await insertRequest('inherited-sender','inherited-recipient')
      for (const status of ['accepted','rejected']) for (const update of ["from_uid='forged-sender'","to_uid='other'","id=9999","message='rewritten'"]) {
        await rejects(asRole('friend_client_inherited','inherited-recipient',`UPDATE public.friend_requests SET status=$2,${update} WHERE id=$1`,[id,status]))
      }
      assert.equal((await ownerQuery('SELECT status FROM public.friend_requests WHERE id=$1',[id])).rows[0].status,'pending')
      assert.equal(await countPair('inherited-sender','inherited-recipient'),0)
      const rejected=await asRole('friend_client_inherited','inherited-recipient',"UPDATE public.friend_requests SET status='rejected' WHERE id=$1 RETURNING status",[id])
      assert.equal(rejected.rows[0].status,'rejected')
    })
    await caseOf('an inherited client role still supports the 130 preparatory insert and a legitimate atomic acceptance', async () => {
      await rejects(asRole('friend_client_inherited','inherited-recipient',"INSERT INTO public.friend_requests(from_uid,to_uid,status) VALUES ('inherited-recipient','author','accepted')"))
      await rejects(asRole('friend_client_inherited','inherited-recipient',"INSERT INTO public.friends(user_uid,friend_uid) VALUES ('inherited-recipient','author')"))
      const id=await insertRequest('inherited-legacy-sender','inherited-recipient')
      const prep=await asRole('friend_client_inherited','inherited-recipient',"INSERT INTO public.friends(user_uid,friend_uid) VALUES ('inherited-recipient','inherited-legacy-sender') RETURNING id")
      assert.equal(prep.rows.length,0);assert.equal(await countPair('inherited-legacy-sender','inherited-recipient'),0)
      const accepted=await asRole('friend_client_inherited','inherited-recipient',"UPDATE public.friend_requests SET status='accepted' WHERE id=$1 RETURNING status",[id])
      assert.equal(accepted.rows[0].status,'accepted');assert.equal(await countPair('inherited-legacy-sender','inherited-recipient'),1)
    })
    await caseOf('131 recipient acceptance confirms the request and edge in one statement', async () => {
      const id = await insertRequest('new-sender','new-recipient')
      assert.equal((await decide('new-recipient',id,'accepted')).rows[0].status, 'accepted')
      assert.equal(await countPair('new-sender','new-recipient'), 1)
      const edge=(await ownerQuery("SELECT * FROM public.friends WHERE user_uid='new-recipient' AND friend_uid='new-sender'")).rows[0]
      assert.equal(edge.friend_name,'Name new-sender')
      assert.equal((await decide('new-recipient',id,'rejected')).rows.length, 0)
      assert.equal((await as('new-recipient',"UPDATE public.friend_requests SET status='pending' WHERE id=$1 RETURNING id",[id])).rows.length, 0)
    })
    await caseOf('130 preparatory edge INSERT succeeds with zero rows; its next state update creates the only edge', async () => {
      const id=await insertRequest('legacy-sender','legacy-recipient')
      const prep=await as('legacy-recipient',"INSERT INTO public.friends(user_uid,friend_uid,friend_name) VALUES ('legacy-recipient','legacy-sender','legacy name') RETURNING id")
      assert.equal(prep.rows.length,0);assert.equal(await countPair('legacy-sender','legacy-recipient'),0)
      assert.equal((await decide('legacy-recipient',id,'accepted')).rows[0].status,'accepted')
      assert.equal(await countPair('legacy-sender','legacy-recipient'),1)
    })
    await caseOf('130 preparatory INSERT followed by failure and rejection leaves no edge', async () => {
      const id=await insertRequest('retry-sender','retry-recipient')
      await as('retry-recipient',"INSERT INTO public.friends(user_uid,friend_uid) VALUES ('retry-recipient','retry-sender')")
      await rejects(as('retry-recipient',"UPDATE public.friend_requests SET status='accepted',from_uid='forged' WHERE id=$1",[id]))
      assert.equal((await decide('retry-recipient',id,'rejected')).rows[0].status,'rejected')
      assert.equal(await countPair('retry-sender','retry-recipient'),0)
    })
    await caseOf('a true edge insertion error rolls back acceptance; rejecting afterward creates no residual friend', async () => {
      await db.exec(`CREATE FUNCTION public.test_edge_fail() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF NEW.friend_uid='edge-fail' THEN RAISE EXCEPTION 'isolated edge failure'; END IF; RETURN NEW; END $$;
        CREATE TRIGGER zz_test_edge_fail BEFORE INSERT ON public.friends FOR EACH ROW EXECUTE FUNCTION public.test_edge_fail();`)
      const id=await insertRequest('edge-fail','failure-recipient')
      await assert.rejects(decide('failure-recipient',id,'accepted'),/isolated edge failure/)
      assert.equal((await ownerQuery('SELECT status FROM public.friend_requests WHERE id=$1',[id])).rows[0].status,'pending')
      assert.equal(await countPair('edge-fail','failure-recipient'),0)
      assert.equal((await decide('failure-recipient',id,'rejected')).rows[0].status,'rejected')
      assert.equal(await countPair('edge-fail','failure-recipient'),0)
      await db.exec('DROP TRIGGER zz_test_edge_fail ON public.friends; DROP FUNCTION public.test_edge_fail()')
    })
    await caseOf('existing reverse edges are preserved and opposite accepted requests do not duplicate them', async () => {
      const one=await insertRequest('pair-A','pair-B'),two=await insertRequest('pair-B','pair-A')
      await decide('pair-B',one,'accepted');await decide('pair-A',two,'accepted')
      assert.equal(await countPair('pair-A','pair-B'),1)
    })
    await caseOf('a deleted relationship cannot be recreated from an old accepted request', async () => {
      const id=await insertRequest('removed-A','removed-B');await decide('removed-B',id,'accepted')
      await as('removed-A',"DELETE FROM public.friends WHERE user_uid='removed-B' AND friend_uid='removed-A'")
      await rejects(as('removed-B',"INSERT INTO public.friends(user_uid,friend_uid) VALUES ('removed-B','removed-A')"))
      assert.equal(await countPair('removed-A','removed-B'),0)
    })
    await caseOf('the real moments RLS exposes friends-only posts after a legitimate decision and keeps private posts owner-only', async () => {
      const id=await insertRequest('author','viewer')
      assert.deepEqual((await as('viewer','SELECT id FROM public.moments ORDER BY id')).rows.map(row=>row.id),[3])
      await decide('viewer',id,'accepted')
      assert.deepEqual((await as('viewer','SELECT id FROM public.moments ORDER BY id')).rows.map(row=>row.id),[1,3])
      assert.deepEqual((await as('author','SELECT id FROM public.moments ORDER BY id')).rows.map(row=>row.id),[1,2,3])
    })
    await caseOf('client cannot execute privileged trigger functions, truncate relationships or attach arbitrary triggers', async () => {
      for (const role of ['authenticated','anon']) for (const name of ['friend_request_guard_131','friend_edge_legacy_insert_131','friend_request_accept_edge_131']) {
        assert.equal((await ownerQuery('SELECT has_function_privilege($1,$2,\'EXECUTE\') AS ok',[role,`public.${name}()`])).rows[0].ok,false)
      }
      for (const table of ['friends','friend_requests']) for (const privilege of ['TRIGGER','TRUNCATE']) {
        assert.equal((await ownerQuery('SELECT has_table_privilege(\'authenticated\',$1,$2) AS ok',[`public.${table}`,privilege])).rows[0].ok,false)
      }
      await rejects(as('attacker','TRUNCATE public.friend_requests'))
    })
    await caseOf('reapplying the migration is idempotent and does not rewrite current business rows', async () => {
      const snapshot=JSON.stringify((await ownerQuery('SELECT * FROM public.friends ORDER BY id')).rows)
      await db.exec(migration)
      assert.equal(JSON.stringify((await ownerQuery('SELECT * FROM public.friends ORDER BY id')).rows),snapshot)
    })
    mkdirSync(resolve(root,'.codex/qa'),{recursive:true})
    writeFileSync(proofPath,JSON.stringify({checked_at:new Date().toISOString(),migration_sha256:migrationHash,postgres_version:(await ownerQuery('SELECT version() AS value')).rows[0].value,engine:'PGlite PostgreSQL WASM; actual RLS, PL/pgSQL and transaction rollback',scope:'Isolated in-memory database only; no production business reads/writes. Opposite request tests run sequentially; not a multi-connection concurrency test.',passed:results.every(row=>row.passed),cases:results},null,2)+'\n')
  } finally { await db.close() }
})
